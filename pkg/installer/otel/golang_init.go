package otel

// goInitFileName is the name of the generated bootstrap file. It is never
// written into the project tree: it is injected at build time via `go build -overlay`.
const goInitFileName = "dtwiz_otel_init.go"

// goInitSource initializes the OpenTelemetry Go SDK (traces, metrics, logs) from an
// init() function so the application's own main() needs no changes. It follows the
// Dynatrace Go walkthrough; endpoint, protocol, temporality and service name are read
// from the OTEL_* environment variables injected at launch, so no secrets are embedded.
const goInitSource = `// Code generated by dtwiz. DO NOT EDIT.

package main

import (
	"context"
	"log"
	"log/slog"
	"net/http"
	"time"

	"github.com/Dynatrace/OneAgent-SDK-for-Go/sdk"
	"go.opentelemetry.io/contrib/bridges/otelslog"
	"go.opentelemetry.io/contrib/instrumentation/net/http/otelhttp"
	otelruntime "go.opentelemetry.io/contrib/instrumentation/runtime"
	"go.opentelemetry.io/otel"
	"go.opentelemetry.io/otel/attribute"
	"go.opentelemetry.io/otel/exporters/otlp/otlplog/otlploghttp"
	"go.opentelemetry.io/otel/exporters/otlp/otlpmetric/otlpmetrichttp"
	"go.opentelemetry.io/otel/exporters/otlp/otlptrace/otlptracehttp"
	"go.opentelemetry.io/otel/log/global"
	"go.opentelemetry.io/otel/propagation"
	sdklog "go.opentelemetry.io/otel/sdk/log"
	sdkmetric "go.opentelemetry.io/otel/sdk/metric"
	"go.opentelemetry.io/otel/sdk/resource"
	sdktrace "go.opentelemetry.io/otel/sdk/trace"
)

func init() {
	ctx := context.Background()

	var attributes []attribute.KeyValue
	for k, v := range sdk.CreateInstance().GetEnrichmentMetadata() {
		attributes = append(attributes, attribute.String(k, v))
	}
	res, err := resource.New(ctx,
		resource.WithFromEnv(),
		resource.WithTelemetrySDK(),
		resource.WithAttributes(attributes...),
	)
	if err != nil {
		log.Printf("dtwiz otel: failed to create resource: %v", err)
		return
	}

	traceExporter, err := otlptracehttp.New(ctx)
	if err != nil {
		log.Printf("dtwiz otel: failed to create trace exporter: %v", err)
		return
	}
	otel.SetTracerProvider(sdktrace.NewTracerProvider(
		sdktrace.WithResource(res),
		sdktrace.WithSampler(sdktrace.AlwaysSample()),
		sdktrace.WithBatcher(traceExporter),
	))
	otel.SetTextMapPropagator(propagation.NewCompositeTextMapPropagator(propagation.TraceContext{}, propagation.Baggage{}))

	metricExporter, err := otlpmetrichttp.New(ctx)
	if err != nil {
		log.Printf("dtwiz otel: failed to create metric exporter: %v", err)
		return
	}
	otel.SetMeterProvider(sdkmetric.NewMeterProvider(
		sdkmetric.WithResource(res),
		sdkmetric.WithReader(sdkmetric.NewPeriodicReader(metricExporter, sdkmetric.WithInterval(10*time.Second))),
	))
	if err := otelruntime.Start(); err != nil {
		log.Printf("dtwiz otel: failed to start runtime metrics: %v", err)
	}

	logExporter, err := otlploghttp.New(ctx)
	if err != nil {
		log.Printf("dtwiz otel: failed to create log exporter: %v", err)
		return
	}
	lp := sdklog.NewLoggerProvider(
		sdklog.WithProcessor(sdklog.NewBatchProcessor(logExporter)),
		sdklog.WithResource(res),
	)
	global.SetLoggerProvider(lp)
	slog.SetDefault(otelslog.NewLogger("dtwiz", otelslog.WithLoggerProvider(lp)))

	// Trace outgoing HTTP calls made through the default client/transport.
	http.DefaultTransport = otelhttp.NewTransport(http.DefaultTransport)
}
`
